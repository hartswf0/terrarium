export const meta = {
  name: 'formicary-round',
  description: 'One improvement round: builder per piece, integrate, then a harsh blind critic per piece',
  phases: [
    { title: 'Build', detail: 'one builder per unfinished piece, each owning disjoint files' },
    { title: 'Integrate', detail: 'build clean, boot clean, chapters playable' },
    { title: 'Judge', detail: 'a separate critic per piece, fresh context, opens the real build' },
  ],
}

const REPO = '/home/user/terrarium'
const R = (args && args.round) || 1
const PIECES = (args && args.pieces) || []

const VERDICT_SCHEMA = {
  type: 'object',
  additionalProperties: false,
  required: ['piece', 'verdict', 'score', 'laws', 'gap', 'evidence', 'firstTimerWalkthrough', 'wouldPickOurs'],
  properties: {
    piece: { type: 'string' },
    verdict: { type: 'string', enum: ['win', 'close', 'lose'] },
    score: { type: 'integer', minimum: 0, maximum: 110 },
    laws: {
      type: 'object', additionalProperties: false,
      required: ['L1', 'L2', 'L3', 'L4', 'L5', 'L6', 'L7', 'L8', 'L9', 'L10', 'L11'],
      properties: {
        L1: { type: 'integer', minimum: 0, maximum: 10 }, L2: { type: 'integer', minimum: 0, maximum: 10 },
        L3: { type: 'integer', minimum: 0, maximum: 10 }, L4: { type: 'integer', minimum: 0, maximum: 10 },
        L5: { type: 'integer', minimum: 0, maximum: 10 }, L6: { type: 'integer', minimum: 0, maximum: 10 },
        L7: { type: 'integer', minimum: 0, maximum: 10 }, L8: { type: 'integer', minimum: 0, maximum: 10 },
        L9: { type: 'integer', minimum: 0, maximum: 10 }, L10: { type: 'integer', minimum: 0, maximum: 10 },
        L11: { type: 'integer', minimum: 0, maximum: 10 },
      },
    },
    gap: { type: 'string', description: 'THE single biggest remaining gap for this piece, stated as one concrete actionable fix' },
    evidence: { type: 'string', description: 'What you actually observed, citing screenshot filenames and probe output' },
    firstTimerWalkthrough: { type: 'string', description: 'What a first-time player literally does, second by second, and where they get lost' },
    wouldPickOurs: { type: 'boolean' },
    shots: { type: 'array', items: { type: 'string' }, description: 'screenshot filenames you produced, relative to formicary/shots/' },
    constraintViolations: { type: 'string' },
  },
}

const COMMON = `
FORMICARY is a single-page playable ecology of multiagent failure, in the repo ${REPO}.
The shipped deliverable is ONE self-contained file, ${REPO}/formicary.html, GENERATED by
\`node formicary/build.js\` from ${REPO}/formicary/src/*. Never edit formicary.html directly.

MANDATORY READING FIRST (Read tool):
  ${REPO}/formicary/AESTHETIC.md       CIVIC NATURALISM — THE GOVERNING DESIGN LAW. Read this FIRST.
                                       It supersedes the original hard rules where they conflict.
  ${REPO}/formicary/RESEARCH.md        the source paper, mapped element by element
  ${REPO}/formicary/CONTRACT.md        the frozen interface — obey exactly
  ${REPO}/formicary/REFERENCE-EOT.md   the TEN-law quality standard; L10 (core loop) is highest priority
  ${REPO}/formicary/src/20-copy.js     every player-facing string lives here

HARD CONSTRAINTS — violating any of these fails the build outright:
  one self-contained HTML file, no network; all 28 elements stay real detectors with real
  effects and working counters; no emoji, drawn marks only; IBM Plex Mono as the only face;
  palette is the MATERIAL/SIGNAL split in AESTHETIC.md section 2 and build.js enforces it.
  RETIRED (do not re-impose): the black-and-white-only palette, the no-border-radius ban,
  the permanent 28-cell table, the permanent six-button tool bar.

HOW TO RUN IT:
  cd ${REPO} && node formicary/build.js
  node formicary/tools/probe.js --name NAME --steps "wait:2000,shot:a" --dump
  node formicary/tools/audit.js
  Screenshots land in ${REPO}/formicary/shots/. Open them with the Read tool and LOOK.

Primary form factor: a 390x844 phone played one-handed.
`

phase('Build')

const builds = await parallel(PIECES.map(p => () => agent(COMMON + `
YOU ARE THE BUILDER FOR PIECE ${p.id} — ${p.name}.

YOU OWN EXACTLY THESE FILES AND NOTHING ELSE:
  ${p.owns}

Other builders are editing the other parts RIGHT NOW. Editing a file you do not own will
destroy their work. If you need a change elsewhere, put the request in your final report.

THIS PIECE IS JUDGED ON: ${p.judged}

${p.brief ? `THE CRITIC'S VERDICT ON THE LAST ROUND OF THIS PIECE:

  BIGGEST GAP: ${p.brief.gap}

  WHAT THEY OBSERVED: ${p.brief.evidence || ''}

  FIRST-TIMER WALKTHROUGH: ${p.brief.firstTimerWalkthrough || ''}

  SCORES: ${JSON.stringify(p.brief.laws || {})}

Close that gap. It is the highest priority thing you do this round. Do not merely acknowledge
it — change the artifact so the observation is no longer true. Then, with remaining effort,
raise the lowest-scoring laws above.` : `This is round 1 for this piece. Read the current state
of the files you own, run the build, screenshot it, and raise it toward the ten laws. L10 — the core loop — is the highest priority.`}

Before you finish:
  1. node formicary/build.js prints BUILD OK
  2. probe prints PAGE ERRORS: none and CONSOLE ERRORS: none
  3. You have taken screenshots of your work and READ them with the Read tool
  4. You have honestly asked: would a stranger, handed this phone, understand this piece in
     three seconds? If not, keep going.

Report: what you changed, how it closes the stated gap, and what you believe the remaining
weakness is.
`, { label: `build:${p.id}`, phase: 'Build', effort: 'high' })))

phase('Integrate')

await agent(COMMON + `
Six builders just edited disjoint parts of FORMICARY concurrently. You are the integrator. You
may edit ANY file in ${REPO}/formicary/src/ — the builders have stopped.

YOUR ONLY JOB is that the integrated artifact builds, boots clean, and plays. Do not redesign.

  1. node formicary/build.js — fix every constraint violation it reports.
  2. node formicary/tools/probe.js --name int${R} --steps "wait:2000,shot:boot,eval:Object.keys(window.FZ)" --dump
     Fix every PAGE ERROR and CONSOLE ERROR. Zero tolerance.
  3. Play it headless through the chapters. Use eval:window.__FZ.goto(N) to jump.
     Verify each chapter renders, its tools appear, and its goal is actually reachable.
     Verify chapter 0 has no tool bar and no table; verify chapter 9 has all 28 cells.
  4. node formicary/tools/audit.js — must reach AUDIT: PASS.
  5. If two builders made contradictory assumptions about the contract, pick the one that
     matches ${REPO}/formicary/CONTRACT.md and make the other conform.

Report: what was broken, what you fixed, the audit result, and which chapters are playable
and winnable right now.
`, { label: 'integrate', phase: 'Integrate', effort: 'high' })

phase('Judge')

const verdicts = await parallel(PIECES.map(p => () => agent(COMMON + `
YOU ARE THE CRITIC FOR PIECE ${p.id} — ${p.name}.

You did not build this. You have no loyalty to it. Your reputation depends on being right, not
on being kind. A critic who passes weak work is worthless.

YOUR DEFAULT VERDICT IS "lose". The artifact must argue you out of it. Ambition, intent, clever
architecture, and good comments earn NOTHING. Score only what a stranger holding a phone would
actually experience.

STEP 1 — OPEN THE REAL RUNNING BUILD. Not the source. The build.
  cd ${REPO} && node formicary/build.js
  Then drive it with probe.js and take your OWN screenshots at a 390x844 phone viewport —
  at minimum: first paint, mid-play, a failure firing, and whatever surface this piece owns.
  Use eval:window.__FZ.goto(N) to reach later chapters, and eval:JSON.stringify(window.__FZ.probe())
  to read state. Prefix every screenshot name with "r${R}${p.id}".
  READ EVERY SCREENSHOT WITH THE READ TOOL. A verdict written without looking at the pixels is
  a fabrication and will be discarded.

STEP 2 — BLIND COMPARISON. ${REPO}/formicary/REFERENCE-EOT.md is the canonical reconstruction of
Nicky Case's "The Evolution of Trust" — the live site is network-blocked here, so that document
IS the opponent. Read it in full. Then, law by law, ask: if these two were open side by side and
I did not know which was which, which one would I rather hand to a stranger?

Score all ELEVEN laws 0-10 honestly. L11 THE DEPICTION LAW is the newest and, with L10, the highest priority: read AESTHETIC.md in full, it is the governing design law and supersedes the original hard rules. L10 (the core loop) is the newest and highest-priority law — it was added after the client played the baseline and said 'not very playable'. Read REFERENCE-EOT.md L10 and section 2B carefully. THIS PIECE IS PRIMARILY JUDGED ON: ${p.judged}
Score the other laws too, as this piece affects them. Every critic scores L10 regardless of piece.
Calibration: 5 = a competent simulation that does not teach. 8 = genuinely as good as The
Evolution of Trust on that law. 10 = better than it. Do not give an 8 you cannot defend with a
specific observation.

STEP 3 — THE FIRST-TIMER WALKTHROUGH. Narrate what a person who has never seen this does,
second by second, from first paint. Where do they hesitate? What do they tap that does nothing?
What do they see that they cannot interpret? Be specific and merciless.

STEP 4 — CHECK THE HARD CONSTRAINTS yourself: grep the built formicary.html for border-radius,
emoji, off-palette hex, and confirm all 28 elements are live detectors (run audit.js). Report
any violation.

STEP 5 — NAME THE SINGLE BIGGEST REMAINING GAP. Exactly one. Not a list. The one thing that,
if fixed, would most raise this piece against the standard. State it as a concrete actionable
change, specific enough that a builder can execute it without asking you a question.

VERDICT RULES — apply them literally:
  "win"   ONLY if every law you scored for this piece's primary criteria is 8 or higher, there
          are no constraint violations, and you would honestly pick ours over The Evolution of
          Trust when handed both blind. Setting wouldPickOurs true is a real claim; do not make
          it to be agreeable.
  "close" the piece is strong but at least one primary law is below 8.
  "lose"  anything else.

HARD RULE: if L10 or L11 scores below 8, the verdict CANNOT be 'win' for any piece, no matter how good the rest is. A build that is not a game does not win, and neither does a build that explains in text what it should have depicted.

You must return the structured object. score is the sum of the eleven laws.
`, { label: `judge:${p.id}`, phase: 'Judge', effort: 'high', schema: VERDICT_SCHEMA })))

return { round: R, verdicts: verdicts.filter(Boolean) }
